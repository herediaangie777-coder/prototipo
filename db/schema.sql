-- ---------------------------------------------------------------------
-- 4. PRODUCTOS (sin stock: el stock sale de los lotes)
--    Fresca    -> se maneja y vende en kg, sin peso por unidad.
--    Congelada -> se maneja y vende en bolsas; peso_unidad_kg = kg por bolsa.
-- ---------------------------------------------------------------------
CREATE TABLE public.productos (
    id_producto            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria           integer NOT NULL,
    tipo_producto          varchar(10) NOT NULL,
    presentacion           varchar(40) NOT NULL,
    unidad_medida          varchar(15) NOT NULL,
    peso_unidad_kg         numeric(8,3),
    precio_compra          numeric(12,2) NOT NULL DEFAULT 0,
    precio_venta_detal     numeric(12,2) NOT NULL DEFAULT 0,
    precio_venta_mayorista numeric(12,2) NOT NULL DEFAULT 0,
    stock_minimo           numeric(12,2) NOT NULL DEFAULT 0,
    estado                 boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_productos_variante UNIQUE (id_categoria, tipo_producto, presentacion),
    CONSTRAINT ck_productos_tipo CHECK (tipo_producto IN ('Fresca', 'Congelada')),
    CONSTRAINT ck_productos_unidad CHECK (
        (tipo_producto = 'Fresca'    AND unidad_medida = 'kg'    AND peso_unidad_kg IS NULL)
     OR (tipo_producto = 'Congelada' AND unidad_medida = 'bolsa' AND peso_unidad_kg IS NOT NULL AND peso_unidad_kg > 0)
    ),
    CONSTRAINT ck_productos_precios CHECK (precio_compra >= 0 AND precio_venta_detal >= 0 AND precio_venta_mayorista >= 0),
    CONSTRAINT ck_productos_stock_minimo CHECK (stock_minimo >= 0),
    CONSTRAINT fk_productos_categoria FOREIGN KEY (id_categoria) REFERENCES public.categorias (id_categoria)
);

