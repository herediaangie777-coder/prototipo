-- ---------------------------------------------------------------------
-- 6. LOTES, PRODUCCIÓN
--    Un lote nace de UNA línea de compra (fresca) o de UNA producción
--    finalizada (congelada). El stock de un producto es la suma de sus lotes.
-- ---------------------------------------------------------------------
CREATE TABLE public.lotes (
    id_lote               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_lote           varchar(20) NOT NULL,
    id_detalle_compra     integer,
    id_detalle_produccion integer,
    fecha_ingreso         date NOT NULL DEFAULT CURRENT_DATE,
    fecha_vencimiento     date NOT NULL,
    tipo_empaque          varchar(10) NOT NULL,
    cantidad_disponible   numeric(12,2) NOT NULL DEFAULT 0,
    id_ubicacion          integer NOT NULL,
    es_transformable      boolean NOT NULL DEFAULT false,
    estado                boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_lotes_numero UNIQUE (numero_lote),
    CONSTRAINT uq_lotes_detalle_compra UNIQUE (id_detalle_compra),
    CONSTRAINT uq_lotes_detalle_produccion UNIQUE (id_detalle_produccion),
    CONSTRAINT ck_lotes_origen CHECK (
        ((id_detalle_compra IS NOT NULL)::int + (id_detalle_produccion IS NOT NULL)::int) = 1
    ),
    CONSTRAINT ck_lotes_fechas CHECK (fecha_vencimiento >= fecha_ingreso),
    CONSTRAINT ck_lotes_empaque CHECK (tipo_empaque IN ('Bulto', 'Caja', 'Bolsa')),
    CONSTRAINT ck_lotes_cantidad CHECK (cantidad_disponible >= 0),
    CONSTRAINT fk_lotes_detalle_compra FOREIGN KEY (id_detalle_compra) REFERENCES public.detalle_compra (id_detalle_compra),
    CONSTRAINT fk_lotes_ubicacion      FOREIGN KEY (id_ubicacion)      REFERENCES public.ubicaciones (id_ubicacion)
);

CREATE TABLE public.produccion (
    id_produccion       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario          integer NOT NULL,
    id_lote_origen      integer NOT NULL,
    fecha_produccion    timestamp NOT NULL DEFAULT LOCALTIMESTAMP,
    cantidad_a_procesar numeric(12,2) NOT NULL,           -- kg de fresa fresca
    merma               numeric(12,2),                    -- se calcula al finalizar
    estado              varchar(12) NOT NULL DEFAULT 'En proceso',
    fecha_finalizacion  timestamp,
    observaciones       varchar(200),
    CONSTRAINT ck_produccion_cantidad CHECK (cantidad_a_procesar > 0),
    CONSTRAINT ck_produccion_estado CHECK (estado IN ('En proceso', 'Finalizada', 'Anulada')),
    CONSTRAINT ck_produccion_merma CHECK (merma IS NULL OR (merma >= 0 AND merma <= cantidad_a_procesar)),
    CONSTRAINT ck_produccion_finalizada CHECK (
        estado <> 'Finalizada' OR (merma IS NOT NULL AND fecha_finalizacion IS NOT NULL)
    ),
    CONSTRAINT fk_produccion_usuario FOREIGN KEY (id_usuario)     REFERENCES public.usuarios (id_usuario),
    CONSTRAINT fk_produccion_lote    FOREIGN KEY (id_lote_origen) REFERENCES public.lotes (id_lote)
);

CREATE TABLE public.detalle_produccion (
