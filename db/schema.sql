-- 9. VISTAS: el stock se calcula desde los lotes
-- ---------------------------------------------------------------------
CREATE VIEW public.v_lotes AS
SELECT l.*, COALESCE(dc.id_producto, dp.id_producto) AS id_producto
FROM public.lotes l
LEFT JOIN public.detalle_compra dc    ON dc.id_detalle_compra    = l.id_detalle_compra
LEFT JOIN public.detalle_produccion dp ON dp.id_detalle_produccion = l.id_detalle_produccion;

CREATE VIEW public.v_stock_producto AS
SELECT t.*, (t.stock_vendible <= t.stock_minimo) AS stock_bajo
FROM (
    SELECT p.id_producto,
           COALESCE(SUM(vl.cantidad_disponible)
                    FILTER (WHERE vl.estado AND vl.fecha_vencimiento >= CURRENT_DATE), 0)::numeric(12,2) AS stock_vendible,
           COALESCE(SUM(vl.cantidad_disponible)
                    FILTER (WHERE vl.estado AND vl.fecha_vencimiento <  CURRENT_DATE), 0)::numeric(12,2) AS stock_vencido,
           p.stock_minimo
    FROM public.productos p
    LEFT JOIN public.v_lotes vl ON vl.id_producto = p.id_producto
    GROUP BY p.id_producto, p.stock_minimo
) t;

